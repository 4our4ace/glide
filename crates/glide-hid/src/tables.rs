use crate::{HidUsage, WinScan};

/// Canonical mapping record between USB HID Usage, Linux evdev keycode,
/// Windows Set 1 scan code, and macOS virtual keycode.
#[derive(Debug, Clone, Copy)]
pub(crate) struct KeyEntry {
    pub name: &'static str,
    pub hid: HidUsage,
    pub evdev: u16,
    pub win: WinScan,
    #[allow(dead_code)]
    pub macos: Option<u16>,
}

const fn kb(usage_id: u16) -> HidUsage {
    HidUsage::keyboard(usage_id)
}

const fn consumer(usage_id: u16) -> HidUsage {
    HidUsage::consumer(usage_id)
}

const fn ws(code: u16) -> WinScan {
    WinScan {
        code,
        extended: false,
    }
}

const fn wse(code: u16) -> WinScan {
    WinScan {
        code,
        extended: true,
    }
}

